# wpms_phase6_steps.py — OUTSIDE WPMS: the host's part of the Phase 6 evidence
# captures, written once and played two ways (as wpms_music.py): Tcl for
# quartus_stp on the board (wpms_issp_host.tcl), and commands for the
# board-level bench (hw/de10_nano/sim/DE10_Nano_wpms_tb.v, driven by
# hw/tools/cosim_board.py). Integers only cross (C3-D1).
#
#   first_go  after the test origin, one GO: a C-major triad on blocks 1-3
#             (sweep [1, 2, 3]); no knob is written, so every sample stays
#             comparable with the model (evidence item 8)
#   full8     one GO arming all eight blocks with the full mask and RT.OUT and
#             the sweep word [0 .. 7]: the full take-set (BCP, item 4) and a
#             full-load sweep, sum of N = NMAX (items 1 and 5)
#   ew6       LE0 = -1 lands in block 0 while it plays: its next packet
#             window's STP raises EW6 (item 6; the switch has no check on LE0)
#
#   python3 wpms_phase6_steps.py [--nmax 1008|2048] [--out DIR]   (writes the .tcl files; both NMAX by default)
# Every GO is followed by a wait for it to be applied; the Tcl prints
# "applied GO g at sweep s" and the bench reads GO_SEQ / APPLIED_SEQ /
# APPLIED_SAMPLE, so hw/tools/phase6_evidence.py knows where each GO landed.
# License: MIT (Layer 3 tooling; not part of the WPMS design).
